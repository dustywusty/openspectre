import assert from 'node:assert/strict';
import http from 'node:http';
import { once } from 'node:events';
import { WebSocket } from 'ws';
import { assetPack } from '../asset-pack.mjs';
import { attachDeathmatch } from '../multiplayer-server.mjs';
const server=http.createServer();const {rooms}=attachDeathmatch(server,{pack:assetPack(process.argv.includes('--open')?'open':process.env.TEST_ASSET_PACK || 'classic')});
server.listen(0,'127.0.0.1');await once(server,'listening');
const url=`ws://127.0.0.1:${server.address().port}/multiplayer/socket`;
const clients=[];
async function client(){
  const ws=new WebSocket(url);clients.push(ws);const queue=[];const waiters=new Set();
  ws.on('message',b=>{const m=JSON.parse(b);queue.push(m);for(const waiter of waiters)waiter();});
  await once(ws,'open');
  return {ws,send:m=>ws.send(JSON.stringify(m)),queue,wait(predicate){return new Promise((resolve,reject)=>{const timer=setTimeout(()=>{waiters.delete(check);reject(new Error(`Timed out: ${predicate}`));},12000);function check(){const index=queue.findIndex(predicate);if(index<0)return;const [m]=queue.splice(index,1);clearTimeout(timer);waiters.delete(check);resolve(m);}waiters.add(check);check();});}};
}
const controls=(throttle=0,steer=0,fire=false)=>({type:'input',throttle,steer,fire,brake:false});
try {
  const a=await client();a.send({type:'create'});const welcomeA=await a.wait(m=>m.type==='welcome');assert.equal(welcomeA.slot,0);
  const waiting=await a.wait(m=>m.type==='state');assert.deepEqual(waiting.connected,[true,false]);assert.equal(waiting.state.tick,0);
  const b=await client();b.send({type:'join',room:welcomeA.room});const welcomeB=await b.wait(m=>m.type==='welcome');assert.equal(welcomeB.slot,1);
  const start=await a.wait(m=>m.type==='state'&&m.connected.every(Boolean));
  console.log('Arena spawn positions',start.state.players.map(p=>[p.x,p.z,p.heading]));
  const c=await client();c.send({type:'join',room:welcomeA.room});assert.match((await c.wait(m=>m.type==='error')).message,/two players/);
  a.send({...controls(1,0,true),slot:1,health:0,kills:500});
  b.send(controls(-1,1,true));
  const moved=await a.wait(m=>m.type==='state'&&m.state.tick>=20);
  assert.notEqual(moved.state.players[0].x,start.state.players[0].x,'host drives');
  assert.notEqual(moved.state.players[1].heading,start.state.players[1].heading,'guest steers');
  assert.ok(moved.state.players.every(p=>p.fired>0),'both players fire');
  assert.ok(moved.state.players.every(p=>p.kills<5),'client cannot assign score');
  const identical=await b.wait(m=>m.type==='state'&&m.state.tick===moved.state.tick);
  assert.deepEqual(identical.state,moved.state,'both clients see the same authoritative state');
  a.send(controls(999,0,true));
  const expired=await a.wait(m=>m.type==='state'&&m.state.tick>=100);
  const later=await a.wait(m=>m.type==='state'&&m.state.tick>=145);
  assert.equal(later.state.players[0].fired,expired.state.players[0].fired,'input expires when sender stops');
  a.send({type:'rematch'});b.send({type:'rematch'});
  const reset=await a.wait(m=>m.type==='state'&&m.state.tick===0&&m.connected.every(Boolean));
  assert.equal(reset.state.players[0].fired,0,'both votes reset match');
  assert.notEqual(reset.round,start.round,'round changes on reset');
  for(let seq=1;seq<=12;seq++)a.send({...controls(1,1),seq,round:reset.round});
  const acknowledged=await a.wait(m=>m.type==='state'&&m.round===reset.round&&m.ack[0]===12);
  assert.ok(acknowledged.state.tick>=12,'queued commands cannot accelerate server time');
  a.send({...controls(1,1),seq:13,round:start.round});
  a.send({...controls(1,1),seq:12,round:reset.round});
  const unchanged=await a.wait(m=>m.type==='state'&&m.round===reset.round&&m.state.tick>acknowledged.state.tick);
  assert.equal(unchanged.ack[0],12,'stale rounds and duplicate inputs ignored');
  a.send({type:'release',round:reset.round});
  b.ws.close();await once(b.ws,'close');
  const disconnected=await a.wait(m=>m.type==='state'&&!m.connected[1]);
  const room=rooms.get(welcomeA.room);room.w.dm_snapshot();
  const read=()=>JSON.parse(new TextDecoder().decode(new Uint8Array(room.w.memory.buffer,room.w.output_ptr(),room.w.output_len())));
  assert.equal(read().tick,disconnected.state.tick);
  c.send({type:'join',room:welcomeA.room});assert.equal((await c.wait(m=>m.type==='welcome')).slot,1);
  const rejoined=await c.wait(m=>m.type==='state'&&m.connected.every(Boolean));assert.equal(rejoined.state.tick,0,'replacement starts a fresh fair match');
  const closed=room.clients.map(ws=>once(ws,'close'));
  a.ws.close();c.ws.close();await Promise.all(closed);
  assert.equal(rooms.size,0,'empty rooms are removed');
  console.log('PASS: room link, two players, shared state, controls, shots, input validation/expiry, full-room rejection, rematch, disconnect/rejoin, cleanup.');
} finally {for(const ws of clients)ws.terminate();server.close();}
